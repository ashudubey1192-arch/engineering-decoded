const slugify = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

const section = (slug, title, lessons) => ({
  slug,
  title,
  lessons: lessons.map((lessonTitle) => ({
    title: lessonTitle,
    slug: `${slug}--${slugify(lessonTitle)}`,
    time: "15 min",
    sectionSlug: slug,
  })),
});

