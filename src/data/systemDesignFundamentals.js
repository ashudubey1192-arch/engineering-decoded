// "+Title" marks a guided lesson: its content lives in src/data/systemDesign/lessons and is
// rendered by SystemDesignLesson. Every other lesson has its own article plus extra depth
// (simulation, subtopics, interview answers) in src/data/systemDesign/deep.
const section = (slug, title, lessons) => ({
  slug,
  title,
  lessons: lessons.map((entry) => {
    const guided = entry.startsWith("+");
    const name = guided ? entry.slice(1) : entry;
    return {
      title: name,
      slug: `${slug}--${name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "")}`,
      time: guided ? "12 min" : "10 min",
      sectionSlug: slug,
      ...(guided ? { guided, updated: "Nov 2026" } : slug === "welcome" ? {} : { depth: true, updated: "Nov 2026" }),
    };
  }),
});

