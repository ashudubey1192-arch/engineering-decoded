function teach(
  id,
  title,
  intro,
  reasoning,
  invariant,
  time,
  space,
  mistake,
  exercise,
  answer,
  steps,
  project,
) {
  const program = javaArrayPrograms[id];
  return {
    ...lesson(
      title,
      intro,
      reasoning,
      invariant,
      undefined,
      { invocation: program.cases[0][0] },
      time,
      space,
      mistake,
      exercise,
      answer,
    ),
    java: {
      id,
      source: javaArraySource(program.method, program.cases[0][0]),
      expected: program.cases[0][1],
    },
    steps,
    project,
    references,
    prerequisites:
      "Java variables, loops, methods, and basic classes. Start with Java essentials, then follow the Arrays lessons in order.",
    boundaries: program.cases.map(([invocation, expected]) => ({ invocation, expected })),
  };
}

