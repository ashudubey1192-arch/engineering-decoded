import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { javaArrayPrograms } from "../src/data/javaArrayPrograms.js";
import { javaArraySource } from "../src/data/javaArrayRuntime.js";

const check = process.argv.includes("--check");
const directory = await mkdtemp(join(tmpdir(), "java-array-lessons-"));
const output = new URL("../src/data/javaArrayTraces.js", import.meta.url);
function execute(command, args) {
  const run = spawnSync(command, args, {
    cwd: directory,
    encoding: "utf8",
    timeout: 60000,
    maxBuffer: 8 * 1024 * 1024,
  });
  if (run.error || run.status !== 0)
    throw new Error(`${command}: ${run.error?.message || run.stderr || run.stdout}`);
  return run.stdout.trim();
}
try {
  const jobs = [];
  for (const [id, program] of Object.entries(javaArrayPrograms)) {
    for (const [index, [invocation, expected]] of program.cases.entries()) {
      const name = `Example${jobs.length}`;
      await writeFile(
        join(directory, `${name}.java`),
        javaArraySource(program.method, invocation, name),
      );
      jobs.push({ id, index, invocation, expected, name, program });
    }
  }
  execute("javac", ["--release", "17", ...jobs.map((job) => `${job.name}.java`)]);
  const traces = {};
  for (const job of jobs) {
    const lines = execute("java", ["-cp", directory, job.name, "--trace"]).split(/\r?\n/);
    const result = JSON.parse(lines.at(-1));
    assert.deepEqual(result, job.expected, `${job.id}: ${job.invocation}`);
    const frames = lines
      .filter((line) => line.startsWith("TRACE\t"))
      .map((line) => JSON.parse(line.slice(6)));
    for (const frame of frames) {
      assert.ok(frame.note.length > 15, `${job.id}: unclear trace note`);
      assert.ok(
        frame.active.every((i) => i >= 0 && i < frame.values.length),
        `${job.id}: invalid active index`,
      );
    }
    if (job.index === 0) {
      assert.ok(frames.length, `${job.id}: worked example needs a trace`);
      traces[job.id] = {
        source: javaArraySource(job.program.method, job.invocation),
        frames,
        result,
      };
    }
  }
  const content = `// Generated by scripts/generate-java-arrays.mjs from executed Java programs.\nexport const javaArrayTraces = ${JSON.stringify(traces, null, 2)};\n`;
  if (check)
    assert.equal(
      await readFile(output, "utf8"),
      content,
      "Java examples changed; regenerate traces",
    );
  else await writeFile(output, content);
  console.log(
    `Compiled and verified ${jobs.length} Java cases across ${Object.keys(traces).length} lessons; ${check ? "checked" : "generated"} matching visual traces.`,
  );
} finally {
  // Only this process's mkdtemp directory is removed; no repository files are touched.
  assert.equal(dirname(resolve(directory)), resolve(tmpdir()));
  assert.ok(basename(directory).startsWith("java-array-lessons-"));
  await rm(directory, { recursive: true, force: true });
}
